  const chassisIndex = (serialInt * 17 + 3) % chassisCount;
  const organismIndex = (serialInt * 29 + 11) % organismCount;
  const anomalyIndex = (serialInt * 7 + 1) % ANOMALY_MODIFIERS.length;

  const chassis = CHASSIS_ITEMS[chassisIndex];
  const organism = ORGANISM_FORMS[organismIndex];

  // Unique Name
  const name = `THE ${chassis.prefix} ${organism.suffix}`;

  // Deterministic Stats
  const power = 30 + ((serialInt * 13) % 65);
  const resonance = 25 + ((serialInt * 19) % 70);
  const stability = 20 + ((serialInt * 23) % 75);
  const density = 40 + ((serialInt * 31) % 55);

  // Rarity calculation based on combination rarity
  let rarity = chassis.rarityBase;
  if (serialInt % 100 === 0) rarity = "MYTHIC";
  else if (serialInt % 25 === 0) rarity = "LEGENDARY";
  else if (serialInt % 10 === 0) rarity = "EPIC";

  const sceneDirection = sceneDirectionFor(serialInt, chassis, organism);

