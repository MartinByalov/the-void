/**
 * Deterministic, non-repeating Artifact Generator based on unique Serial Number
 * 
 * Uses a co-prime permutation algorithm so sequential IDs generate radically
 * diverse, non-colliding pairings across the entire integer space.
 */
export function getArtifactBySerial(serialNumber) {
  const serialInt = parseInt(serialNumber, 10) || 1;
  const serialStr = `VA-${String(serialInt).padStart(6, '0')}`;

  const chassisCount = CHASSIS_ITEMS.length;
  const organismCount = ORGANISM_FORMS.length;
  const totalCombinations = chassisCount * organismCount; // 48 * 45 = 2160 primary seeds

  // Deterministic permutation strides
  const chassisIndex = (serialInt * 17 + 3) % chassisCount;
  const organismIndex = (serialInt * 29 + 11) % organismCount;
  const anomalyIndex = (serialInt * 7 + 1) % ANOMALY_MODIFIERS.length;

  const chassis = CHASSIS_ITEMS[chassisIndex];
  const organism = ORGANISM_FORMS[organismIndex];

  // Unique Name
  const name = `THE ${chassis.prefix} ${organism.suffix}`;

  // Deterministic Stats
  const power = 30 + ((serialInt * 13) % 65);
  const resonance = 25 + ((serialInt * 19) % 70);
  const stability = 20 + ((serialInt * 23) % 75);
  const density = 40 + ((serialInt * 31) % 55);

  // Rarity calculation based on combination rarity
  let rarity = chassis.rarityBase;
  if (serialInt % 100 === 0) rarity = "MYTHIC";
  else if (serialInt % 25 === 0) rarity = "LEGENDARY";
  else if (serialInt % 10 === 0) rarity = "EPIC";

  const artifact = artifactDescriptionFor(serialInt, chassis, organism);
  const artifactDescription = artifact.text;
  const scene = sceneDirectionFor(serialInt, chassis, organism);
  const sceneDirection = scene.text;
  const prompt = promptFor(name, artifactDescription, sceneDirection);

  return {
    id: serialStr,
    serialNumber: serialInt,
    name: name,
    rarity: rarity,
    weirdness: (45 + (serialInt * 11) % 50) / 10,
    taxonomy: {
      chassis_synset: chassis.noun,
      chassis_name: chassis.name,
      organism_synset: organism.noun,
      organism_name: organism.name,
      category: chassis.category,
      classType: organism.classType
    },
    stats: {
      power: power,
      resonance: resonance,
      stability: stability,
      density: density
    },
    anomaly: ANOMALY_MODIFIERS[anomalyIndex],
    description: `A synthetic entity uniting ${chassis.name.toLowerCase()} engineering with the living morphology of a ${organism.name.toLowerCase()}. ${ANOMALY_MODIFIERS[anomalyIndex]}`,
    artifactDescription,
    fusion: artifact.fusion,
    scene,
    sceneDirection,
    style: THE_VOID_STYLE,
    prompt: prompt
  };
}

/**
 * Generate a batch of N unique sequential artifacts starting from startSerial
 */
export function generateBatchRegistry(startSerial = 1, count = 100) {
  const batch = [];
  for (let i = 0; i < count; i++) {
    batch.push(getArtifactBySerial(startSerial + i));
  }
  return batch;
}
